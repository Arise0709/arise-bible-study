  p.on('pageerror', (e) => errors.push(e.message))
  const panel = () => p.locator('div.panel[aria-label="Study tools"]')

  console.log('1. Bible navigation and search')
  await p.goto(BASE + '/bible/Gen/1', { waitUntil: 'networkidle' })
