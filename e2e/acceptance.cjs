  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'abs-export-'))
  for (const [label, ext] of [['.md', 'md'], ['Word', 'docx'], ['PDF', 'pdf']]) {
    const [dl] = await Promise.all([p.waitForEvent('download'), p.getByRole('button', { name: label, exact: true }).click()])
    const f = path.join(dir, `out.${ext}`)
    await dl.saveAs(f)
    check(`${ext} export downloaded`, fs.statSync(f).size > 500)
  }
  const md = fs.readFileSync(path.join(dir, 'out.md'), 'utf8')
  check('markdown keeps title, headings, quotation, notes', md.startsWith('# God So Loved') && md.includes('## ') && md.includes('For God so loved the world') && md.includes('(KJV)') && md.includes('Here God loves the whole world'), md.slice(0, 900))
  const docxText = execSync(`unzip -p ${path.join(dir, 'out.docx')} word/document.xml`).toString()
  const hdr = execSync(`unzip -p ${path.join(dir, 'out.docx')} word/header1.xml word/footer1.xml`).toString()
  check('docx shows series line and secondary title', docxText.includes('THE LOVE OF GOD, PART 1 OF 3') && docxText.includes('Love that gives') && docxText.includes('Series: The Love of God, Part 1 of 3'))
  check('docx uses the church notes template (header, footer, styles)', hdr.includes('GOD SO LOVED') && hdr.includes('John 3:16-17 | KJV') && hdr.includes('Sermon Manuscript') && docxText.includes('w:fill="F7F6F2"') && !docxText.includes('Nazareth'))
  check('docx keeps headings, quotation, notes', docxText.includes('GOD SO LOVED') && docxText.includes('Heading1') && docxText.includes('For God so loved the world') && docxText.includes('Here God loves the whole world'))
  check('pdf is a PDF', fs.readFileSync(path.join(dir, 'out.pdf')).subarray(0, 5).toString() === '%PDF-')
  let pdfText = ''
  try {
    pdfText = execSync(`pdftotext ${path.join(dir, 'out.pdf')} -`).toString()
  } catch {
    /* pdftotext not installed */
  }
  if (pdfText) {
    check('pdf follows the notes template (title, header, footer, quotation, notes)', pdfText.includes('GOD SO LOVED') && pdfText.includes('Sermon Manuscript') && pdfText.includes('John 3:16-17 | KJV') && pdfText.includes('For God so loved the world') && pdfText.includes('Here God loves the whole world'), pdfText.slice(0, 400))
    check('pdf embeds the Inter font', execSync(`pdffonts ${path.join(dir, 'out.pdf')}`).toString().includes('Inter-'))
  }

